def _mixed_bundle(a):
    # With --llm-extract the bundle composition comes from the LLM (bundle_key); otherwise
    # fall back to the `+` heuristic, which looks for a `+` outside parentheses in the raw
    # title and so misreads age markers such as `0M+` as bundles.
    if 'bundle_key' in a:
        return a['bundle_key'] is not None
    title = a['raw'].get('sku_name_chi') or ''
    # Ingredient lists often contain '+' inside parentheses; only a plus sign
    # outside parentheses is evidence of a mixed-flavour bundle.
    outside = re.sub(r'[\(（][^\(\)（）]*[\)）]', ' ', title)
    return a.get('pack_count', 1) > 1 and '+' in outside


def _formulation_conflict(a, b, tol=0.5):
    """Same ingredient, different percentage -> conflict (12%月桂油 ≠ 40%月桂油); missing is not."""
    fa, fb = a.get('formulation'), b.get('formulation')
    if not fa or not fb:
        return False
    da, db = dict(fa), dict(fb)
    return any(abs(da[name] - db[name]) > tol for name in set(da) & set(db))


def hard_veto(a, b, sigs=None, alt=None):
    """Known conflicts only. Missing attributes are never treated as conflict."""
    fa, fb = a.get('form'), b.get('form')
    if fa != 'UNKNOWN' and fb != 'UNKNOWN' and fa != fb:
        return True
    va, vb = a.get('unit_value'), b.get('unit_value')
    if va is not None and vb is not None:
        if not unit_compatible((va, a.get('unit_uom')), (vb, b.get('unit_uom'))):
            return True
    if not origin_compatible(a.get('origin', frozenset()), b.get('origin', frozenset())):
        return True
    if _mixed_bundle(a) != _mixed_bundle(b):
        return True
    ka, kb = a.get('bundle_key'), b.get('bundle_key')
    if ka is not None and kb is not None and ka != kb:
        return True                                   # both are bundles, but of different items
    if _formulation_conflict(a, b):
        return True                                   # formulation % conflict = different products
    if sigs is not None and alt is not None:
        if V.variant_conflict(sigs[a['sku_id']], sigs[b['sku_id']], alt):
            return True
    # Deliberately no fixed ean[:7] cannot-link: GS1 company-prefix length is variable.
    return False


def _embedding_map(rows, matrix):
    if matrix is None:
        return None
    return {r['sku_id']: matrix[i] for i, r in enumerate(rows)}


def feature_vector(a, b, ctx, embedding_by_sku=None, image_by_sku=None,
                   auxiliary_embedding_by_sku=None):
    base = F.pair_features(a, b, ctx['sigs_feat'], ctx['resid'], ctx['idf'], ctx['n'],
                           ctx['veto'], ctx['kvt'])
    out = [base[i] for i in F.MODEL_IDX]
    if embedding_by_sku is not None:
        out.append(float(np.dot(embedding_by_sku[a['sku_id']],
                                embedding_by_sku[b['sku_id']])))
    if auxiliary_embedding_by_sku is not None:
        out.append(float(np.dot(auxiliary_embedding_by_sku[a['sku_id']],
                                auxiliary_embedding_by_sku[b['sku_id']])))
    if image_by_sku is not None:
        out.extend(IMG.pair_features(a['sku_id'], b['sku_id'], image_by_sku))
    return out


def train(rows, ctx, embedding_by_sku=None, image_by_sku=None,
          auxiliary_embedding_by_sku=None):
    data, ean = make_labels(rows, ctx)
    A = ctx['attrs']
    X = np.asarray([feature_vector(A[a], A[b], ctx, embedding_by_sku, image_by_sku,
                                   auxiliary_embedding_by_sku)
                    for a, b, _, _ in data], dtype=float)
    y = np.asarray([lab for _, _, lab, _ in data], dtype=float)
    npos = int(y.sum())
    w = np.where(y == 1, (len(y) - npos) / max(1, npos), 1.0)
    fa = np.asarray([fold_of(a, ean) for a, _, _, _ in data])
    fb = np.asarray([fold_of(b, ean) for _, b, _, _ in data])
    keep = fa == fb
    X, y, w, folds = X[keep], y[keep], w[keep], fa[keep]

    full = GBDT(n_trees=180, lr=0.07, max_depth=3, seed=503).fit(X, y, w)
    oof = {}
    for k in range(N_FOLDS):
        tr = folds != k
        if y[tr].sum() < 1:
            continue
        oof[k] = GBDT(n_trees=180, lr=0.07, max_depth=3,
                      seed=500 + k).fit(X[tr], y[tr], w[tr])

    def model_for(a, b):
        ka = fold_of(a, ean) if ean.get(a) else None
        kb = fold_of(b, ean) if ean.get(b) else None
        if ka is not None and ka == kb and ka in oof:
            return oof[ka]
        return full

    return full, model_for, {'n_pairs': int(len(y)), 'n_pos': int(y.sum())}


def score_candidates(candidate_info, attrs, ctx, model_for, embedding_by_sku,
                     use_ean_must_link, image_by_sku=None,
                     auxiliary_embedding_by_sku=None):
    score = {}
    regular = []
    for (a, b), rec in candidate_info.items():
        aa, bb = attrs[a], attrs[b]
        if use_ean_must_link and aa['ean'] and bb['ean'] and (aa['ean'] & bb['ean']):
            # Exact GTIN may override noisy statistically-mined variant tokens,
            # but never an independently observed form/unit/origin conflict.
            score[(a, b)] = (None if hard_veto(aa, bb) else 1.0)
            continue
        if hard_veto(aa, bb, ctx['sigs'], ctx['veto']):
            score[(a, b)] = None
            continue
        same_title = C.packfree_key(aa) and C.packfree_key(aa) == C.packfree_key(bb)
        brand_ok = (aa.get('brand_key') == bb.get('brand_key')
                    or not aa.get('brand_key') or not bb.get('brand_key'))
        if same_title and brand_ok:
            score[(a, b)] = 1.0
            continue
        # Business invariant: package count is not a product identity field.
        # Brand + unit/form/origin hard compatibility + the same non-empty,
        # cleaned variant signature are sufficient identity evidence. Requiring
        # extra word-order similarity here incorrectly split paraphrases such as
        # "麝香琥珀" vs "麝香與琥珀" solely because one listing was a 4-pack.
        sa, sb = ctx['sigs_feat'][a], ctx['sigs_feat'][b]
        if (aa.get('pack_count') != bb.get('pack_count')
                and aa.get('brand_key') and aa.get('brand_key') == bb.get('brand_key')
                and sa and sa == sb):
            score[(a, b)] = 1.0
            continue
        regular.append((a, b))

    if regular:
        X = np.asarray([feature_vector(attrs[a], attrs[b], ctx, embedding_by_sku,
                                       image_by_sku, auxiliary_embedding_by_sku)
                        for a, b in regular], dtype=float)
        buckets = collections.defaultdict(list)
        models = {}
        for i, (a, b) in enumerate(regular):
            model = model_for(a, b)
            models[id(model)] = model
            buckets[id(model)].append(i)
        for mid, idx in buckets.items():
            pred = models[mid].predict_proba(X[idx])
            for i, value in zip(idx, pred):
                score[regular[i]] = float(value)
    return score


def constrained_clusters(attrs, scores, threshold, sigs=None, alt=None, must_links=None):
    """Greedy sparse agglomeration with cluster-level cannot-link checks.

    A candidate edge can merge two clusters only when every cross-member pair
    is hard-compatible and the average *known* edge score (missing=0) remains
    above the threshold. This blocks transitive snowballs through missing data.
    """
    parent = {sid: sid for sid in attrs}
    members = {sid: {sid} for sid in attrs}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def clusters_compatible(ma, mb):
        for x in ma:
            for y in mb:
                exact_ean = (attrs[x]['ean'] and attrs[y]['ean']
                             and bool(attrs[x]['ean'] & attrs[y]['ean']))
                vetoed = (hard_veto(attrs[x], attrs[y]) if exact_ean
                          else hard_veto(attrs[x], attrs[y], sigs, alt))
                if vetoed:
                    return False
        return True

    def union(ra, rb):
        keep, drop = (ra, rb) if ra < rb else (rb, ra)
        parent[drop] = keep
        members[keep] |= members.pop(drop)

    # Must-links express identity evidence, so merge them before probabilistic
    # edges. Otherwise a growing cluster's missing cross-edge scores can stop
    # two listings with the exact same GTIN from ever meeting.
    for a, b in sorted(must_links or ()):
        ra, rb = find(a), find(b)
        if ra != rb and clusters_compatible(members[ra], members[rb]):
            union(ra, rb)

    edges = [(value, a, b) for (a, b), value in scores.items()
             if value is not None and value >= threshold
             and (a, b) not in (must_links or set())]
    edges.sort(key=lambda x: (-x[0], x[1], x[2]))
    for edge_score, a, b in edges:
        ra, rb = find(a), find(b)
        if ra == rb:
            continue
        ma, mb = members[ra], members[rb]
        values = []
        allowed = clusters_compatible(ma, mb)
        if not allowed:
            continue
        for x in ma:
            for y in mb:
                value = scores.get((x, y) if x < y else (y, x), 0.0)
                if value is None:
                    allowed = False
                    break
                values.append(value)
            if not allowed:
                break
        if not allowed or not values or sum(values) / len(values) < threshold:
            continue
        union(ra, rb)

    groups = collections.OrderedDict()
    for sid in sorted(attrs):
        root = find(sid)
        groups.setdefault(root, []).append(attrs[sid])
    return groups


def metrics(groups, rows, attrs, sigs, candidate_info=None, label_attrs=None):
    gid = {}
    for key, ms in groups.items():
        for m in ms:
            gid[m['sku_id']] = key
    pos = silver_pairs(rows)
    # ⚠️ Silver negatives are built from pack_count/unit, and --llm-extract rewrites both.
    # Labelling from the overridden attrs would let the two extraction modes report against
    # different denominators, so label_attrs pins the regex-extracted snapshot: the denominator
    # cannot drift with the configuration under evaluation (same idea as the frozen pack file).
    neg = silver_negatives(rows, pos, label_attrs if label_attrs is not None else attrs)
    # 🚨 Prefer the frozen test set. Recomputing ties the denominator to the variant vocabulary,
    # so shrinking that vocabulary can break pack invariance and still print 100%
    # (measured: 85 -> 84 hid 7 pairs).
    inv = (load_packcount_pairs(PACK_PAIRS_PATH) if PACK_PAIRS_PATH.exists()
           else packcount_invariance_pairs(rows, attrs, sigs))
    tp = sum(gid.get(a) == gid.get(b) for a, b in pos)
    fp = sum(gid.get(a) == gid.get(b) for a, b in neg)
    pc = sum(gid.get(a) == gid.get(b) for a, b in inv)
    sizes = collections.Counter(len(ms) for ms in groups.values())
    return {
        'n_groups': len(groups), 'n_singletons': sizes[1], 'max_group': max(sizes),
        'silver_recall': tp / len(pos),
        'silver_tp': tp, 'silver_pos': len(pos),
        'silver_negative_merge_rate': fp / max(1, len(neg)),
        'silver_fp': fp, 'silver_neg': len(neg),
        # This is case-control sample precision, not population precision.
        'case_control_precision': tp / max(1, tp + fp),
        'pack_invariance': pc / max(1, len(inv)),
        'pack_invariance_ok': pc, 'pack_invariance_n': len(inv),
        'candidate_recall': (sum((a, b) in candidate_info for a, b in pos) / len(pos)
                             if candidate_info is not None else None),
        'n_candidates': len(candidate_info) if candidate_info is not None else None,
    }


def choose_threshold(curve):
    eligible = [(t, m) for t, m in curve.items()
                if m['silver_negative_merge_rate'] <= 0.025
                and m['pack_invariance'] >= 0.98]
    if eligible:
        return max(eligible, key=lambda tm: (tm[1]['silver_recall'],
                                             tm[1]['case_control_precision'], tm[0]))[0]
    return max(curve, key=lambda t: (curve[t]['case_control_precision']
                                     * curve[t]['silver_recall'], t))


def write_groups(path, groups, stable_ids, ctx, dataset_hash, representation):
    resid = ctx['resid']
    with open(path, 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerow(['sku_id', 'group_id', 'group_name', 'group_size', 'brand_canonical',
                    'product_form', 'unit', 'origin', 'pack_count', 'ean', 'sku_name',
                    'method_version', 'dataset_sha256'])
        # Name disambiguation: the same group_name under two different group_ids reads like
        # a grouping bug. Pure post-processing -- it only reads the already-assigned
        # stable_ids and cannot change the clustering.
        names = G.disambiguate_names(groups, ctx['sigs'], stable_ids)
        for key, ms in sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            gid = stable_ids[key]
            name = names[key]
            for m in ms:
                w.writerow([m['sku_id'], gid, name, len(ms), m['brand_canonical'] or '',
                            m['form'], ('%g%s' % (m['unit_value'], m['unit_uom']))
                            if m['unit_value'] is not None else '',
                            '/'.join(sorted(m['origin'])), m['pack_count'],
                            ';'.join(sorted(m['ean'])), m['raw']['sku_name_chi'],
                            METHOD_VERSION + '-' + representation, dataset_hash])


def write_candidate_scores(path, info, scores):
    with open(path, 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerow(['sku_a', 'sku_b', 'score', 'sources', 'embedding_cosine'])
        for pair in sorted(info):
            rec = info[pair]
            value = scores.get(pair)
            w.writerow([pair[0], pair[1], '' if value is None else '%.8f' % value,
                        ';'.join(sorted(rec['sources'])),
                        '' if rec['embedding_cosine'] is None else '%.8f' % rec['embedding_cosine']])


def main(path=PROCESSED_DATASET_PATH, method='method_3_semantic', allow_api=True,
         use_form=True, use_ann=False, use_llm=False):
    if method not in REPRESENTATION:
        raise ValueError('unknown method: %s (choices: %s)' % (method, ', '.join(METHODS)))
    representation = REPRESENTATION[method]
    if use_llm and representation not in ('semantic', 'semantic_image', 'hybrid_fusion'):
        raise ValueError('--llm-extract applies to the online methods only (3/4/5); '
                         'the whole point of methods 1/2 is that no data leaves the machine')
    ensure_dirs()
    out_dir = method_dir(method, use_form=use_form, use_ann=use_ann, use_llm=use_llm)
    out_dir.mkdir(parents=True, exist_ok=True)

    # Per-stage wall-clock time. Written to report.json; evaluate_all rolls it into metrics.csv.
    timing = {}
    t_engine = time.perf_counter()

    def _lap(name, start):
        timing[name] = round(time.perf_counter() - start, 3)

    t0 = time.perf_counter()
    rows = load(path)
    ctx = build_context(rows, use_form=use_form)
    attrs = ctx['attrs']
    _lap('load_and_context_seconds', t0)
    # --llm-extract: the LLM reads, the code verifies, then it conservatively overrides the
    # regex attributes. ⚠️ Evaluation labels are built from the pre-override attribute
    # snapshot (label_attrs), so the denominator does not drift with the extraction mode.
    label_attrs = None
    llm_meta = None
    if use_llm:
        t0 = time.perf_counter()
        label_attrs = {sid: dict(a) for sid, a in attrs.items()}
        llm_by_sku, llm_meta = LLME.extract_all(
            rows, LLM_EXTRACT_CACHE_DIR, env_path=PROJECT_ROOT / '.env',
            allow_api=allow_api)
        llm_meta['override_stats'] = LLME.apply_overrides(
            attrs, ctx['sigs'], ctx['sigs_feat'], llm_by_sku, rows)
        _lap('llm_extract_seconds', t0)
    embeddings = None
    embedding_meta = None
    auxiliary_embeddings = None
    auxiliary_embedding_meta = None
    image_by_sku = None
    image_meta = None
    t0 = time.perf_counter()
    if representation in ('semantic', 'semantic_image', 'hybrid_fusion'):
        embeddings, embedding_meta = load_or_create(
            rows, attrs, cache_dir=CACHE_DIR,
            env_path=PROJECT_ROOT / '.env', allow_api=allow_api)
    elif representation == 'local_tfidf':
        embeddings, embedding_meta = build_local_vectors(rows, attrs)
    if representation == 'hybrid_fusion':
        # Semantic vectors align paraphrases across writing styles; local hashed TF-IDF keeps
        # rare surface tokens such as exact model numbers, scents and short codes. The two are
        # fused late, at the pairwise layer, rather than collapsed early into one opaque score.
        auxiliary_embeddings, auxiliary_embedding_meta = build_local_vectors(rows, attrs)
    if representation in ('semantic_image', 'hybrid_fusion'):
        # Images are extra evidence for the pairwise scorer, not an assumption that a more
        # similar photo means the same product -- see lib/images.py. Image near-duplicates
        # could also be a sixth retrieval channel (image_pairs in candidates.generate), but
        # the ablation showed zero gain: every new pair it surfaced was dropped by the hard
        # attribute checks in broad_compatible, leaving all four metrics unchanged to the
        # last digit. Evidence in docs/research/image_signal.txt §3.
        image_by_sku, image_meta = IMG.build(rows, IMAGE_CACHE_DIR,
                                             allow_download=allow_api)
    # ANN is optional: precompute the neighbour table and pass it to candidates.generate via
    # its semantic_neighbors hook. Off by default -- on 1472 rows exact retrieval is faster
    # with no recall loss, see lib/ann.py.
    neighbours, ann_meta = None, None
    if use_ann and embeddings is not None:
        neighbours, ann_meta = ANN.top_k([embeddings[i] for i in range(len(rows))],
                                         [r['sku_id'] for r in rows])
    _lap('representation_seconds', t0)
    embedding_by_sku = _embedding_map(rows, embeddings)
    auxiliary_embedding_by_sku = _embedding_map(rows, auxiliary_embeddings)
    primary_embedding_feature = {
        'local_tfidf': 'local_tfidf_cosine',
        'semantic': 'semantic_cosine',
        'semantic_image': 'semantic_cosine',
        'hybrid_fusion': 'semantic_cosine',
    }.get(representation)
    feature_names = (list(F.MODEL_FEATURES)
                     + ([primary_embedding_feature]
                        if primary_embedding_feature is not None else [])
                     + (['local_tfidf_cosine']
                        if auxiliary_embeddings is not None else [])
                     + (list(IMG.FEATURE_NAMES) if image_by_sku is not None else []))
    t0 = time.perf_counter()
    full, model_for, train_meta = train(rows, ctx, embedding_by_sku, image_by_sku,
                                        auxiliary_embedding_by_sku)
    _lap('train_seconds', t0)

    # Honest evaluation excludes exact-EAN and fixed-length GS1 retrieval hints.
    t0 = time.perf_counter()
    honest_info = C.generate(attrs, None if use_ann else embeddings,
                             include_ean=False, include_legacy_hint=False,
                             semantic_neighbors=neighbours)
    honest_scores = score_candidates(honest_info, attrs, ctx, model_for,
                                     embedding_by_sku, use_ean_must_link=False,
                                     image_by_sku=image_by_sku,
                                     auxiliary_embedding_by_sku=auxiliary_embedding_by_sku)
    honest_must = {pair for pair, value in honest_scores.items() if value == 1.0}
    curve = {}
    honest_groups = {}
    for threshold in THRESHOLDS:
        gs = constrained_clusters(attrs, honest_scores, threshold, ctx['sigs'], ctx['veto'],
                                  honest_must)
        honest_groups[threshold] = gs
        curve[threshold] = metrics(gs, rows, attrs, ctx['sigs'], honest_info,
                                   label_attrs=label_attrs)
    selected = FIXED_OPERATING_POINTS.get(method, choose_threshold(curve))
    if selected not in curve:
        raise ValueError('fixed operating point %.4f is not in THRESHOLDS' % selected)
    _lap('honest_sweep_seconds', t0)

    t0 = time.perf_counter()
    production_info = C.generate(attrs, None if use_ann else embeddings,
                                 include_ean=True, include_legacy_hint=True,
                                 semantic_neighbors=neighbours)
    production_scores = score_candidates(production_info, attrs, ctx, model_for,
                                         embedding_by_sku, use_ean_must_link=True,
                                         image_by_sku=image_by_sku,
                                         auxiliary_embedding_by_sku=auxiliary_embedding_by_sku)
    production_must = {pair for pair, value in production_scores.items() if value == 1.0}
    production_groups = constrained_clusters(attrs, production_scores, selected,
                                              ctx['sigs'], ctx['veto'], production_must)

    _lap('production_seconds', t0)

    t0 = time.perf_counter()
    suffix = representation
    group_path = out_dir / 'groups.csv'
    stable, lineage = assign_group_ids(production_groups, previous_path=group_path)
    dataset_hash = file_sha256(path)
    write_groups(group_path, production_groups, stable, ctx, dataset_hash, suffix)
    write_candidate_scores(out_dir / 'candidate_pairs.csv',
                           production_info, production_scores)
    with open(out_dir / 'group_lineage.csv',
              'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=['group_id', 'previous_group_id', 'relation',
                                          'overlap', 'jaccard'], lineterminator='\n')
        w.writeheader(); w.writerows(lineage)
    full.save(out_dir / 'model.json', metadata={
        'method_version': METHOD_VERSION, 'feature_names': feature_names,
        'dataset_sha256': dataset_hash, **train_meta,
    })
    _lap('write_seconds', t0)
    timing['engine_seconds'] = round(time.perf_counter() - t_engine, 3)

    report = {
        'method_version': METHOD_VERSION, 'method': method,
        'representation': representation, 'dataset_sha256': dataset_hash,
        'config': {'use_form': bool(use_form), 'use_ann': bool(use_ann),
                   'use_llm': bool(use_llm)},
        'ann': ann_meta,
        'feature_names': feature_names, 'train': train_meta,
        'embedding': embedding_meta,
        'auxiliary_embedding': auxiliary_embedding_meta,
        'image': image_meta,
        'llm_extraction': llm_meta,
        'timing': timing,
        'candidate_sources_honest': dict(C.source_counts(honest_info)),
        'candidate_sources_production': dict(C.source_counts(production_info)),
        'selected_threshold': selected,
        'threshold_policy': ('fixed_operating_point'
                             if method in FIXED_OPERATING_POINTS else 'release_gate_auto'),
        'curve_honest': {str(t): m for t, m in curve.items()},
        # The single evaluation contract shared by all five methods: evaluate_all reads this
        # key and never parses the human-readable report.
        'metrics': curve[selected],
        'production': metrics(production_groups, rows, attrs, ctx['sigs'], production_info,
                              label_attrs=label_attrs),
    }
    report_path = out_dir / 'report.json'
    with open(report_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, ensure_ascii=False, indent=2)

    print('=' * 88)
    print('%s | n=%d | features=%d | honest candidates=%d | candidate recall=%.1f%% | engine time=%.1fs' % (
        method, len(rows), len(feature_names), len(honest_info),
        curve[selected]['candidate_recall'] * 100, timing['engine_seconds']))
    print('=' * 88)
    print('  %6s %7s %7s %8s %9s %10s %9s %10s' % (
        'thresh', 'groups', 'singles', 'largest', 'recall', 'negmerge', 'sample-P', 'pack-inv'))
    for t in THRESHOLDS:
        m = curve[t]
        mark = '  <- selected' if t == selected else ''
        print('  %6.2f %7d %7d %8d %8.1f%% %9.1f%% %8.1f%% %9.1f%%%s' % (
            t, m['n_groups'], m['n_singletons'], m['max_group'],
            m['silver_recall'] * 100, m['silver_negative_merge_rate'] * 100,
            m['case_control_precision'] * 100, m['pack_invariance'] * 100, mark))
    print('\nWrote:', group_path)
    print('Report:', report_path)
    return report


